export function getLang() {
  try {
    const v = localStorage.getItem("cvmaker_lang");
    if (v === "hi" || v === "en") return v;
  } catch (_) {}
  return "hi"; // default Hindi for easier local use
}

export function setLang(lang) {
  try {
    localStorage.setItem("cvmaker_lang", lang === "hi" ? "hi" : "en");
  } catch (_) {}
}

export function t(lang, key) {
  const pack = dict[lang] || dict.hi;
  return pack[key] || dict.en[key] || key;
}

export default dict;
