// ============================================================
// server/serverPdf.js
// ------------------------------------------------------------
// Responsibilities:
//   1. sanitizeResumeSnapshot()   → clean + size-cap paid order data
//   2. issueServerPdfToken()      → HMAC token for server-side PDF render
//   3. verifyServerPdfToken()     → verify that token
//   4. getServerPdfSnapshot()     → fetch stored snapshot from Firestore
//   5. claimEmailDelivery()       → idempotency lock for email sends
//   6. markEmailDelivered()       → mark success
//   7. markEmailDeliveryFailed()  → mark failure
//
// IMPORTANT: Photos (data URLs) are NEVER stored in Firestore order
// snapshots. A single base64 photo is 100KB–2MB, which blows both our
// own 60KB snapshot cap AND the Firestore 1MB doc limit. The paid PDF
// email is generated by rendering the app server-side; the photo is
// not required for that flow.
// ============================================================

import crypto from 'node:crypto';
import { db, FieldValue } from './firebaseAdmin.js';

// ---------- Limits ----------
const MAX_STRING_FIELD = 2000;
const MAX_SNAPSHOT_BYTES = 300000; // Firestore doc limit is 1MB; stay well under

// Per-field caps for known long-text areas. Anything not listed falls
// back to MAX_STRING_FIELD.
const FIELD_CAPS = {
  summary: 2500,
  workExperience: 6000,
  familyDetails: 2500,
  expectations: 2500,
  address: 500,
  hobbies: 500,
  fatherName: 200,
  motherName: 200,
  fatherOccupation: 200,
  motherOccupation: 200,
  brother: 500,
  sister: 500,
  company: 200,
  occupation: 200,
  role: 200,
  gradCourse: 200,
  gradCollege: 250,
  gradUniv: 250,
  interSchool: 250,
  sscSchool: 250,
};

const asString = (v, max = MAX_STRING_FIELD) => String(v ?? '').slice(0, max);

// ============================================================
// 1. SANITIZE RESUME SNAPSHOT
// ============================================================
/**
 * Strips the incoming resume payload down to safe, size-capped fields.
 * Throws if the resulting snapshot is too large to store reliably.
 *
 * Photos (photo / photoRaw) are intentionally EXCLUDED.
 *
 * @param {object} input - { ...resumeData, designSettings, selectedTemplateId, colorPaletteId }
 * @returns {{ resumeData: object, designSettings: object, selectedTemplateId: string, colorPaletteId: string }}
 */
export function sanitizeResumeSnapshot(input = {}) {
  const {
    designSettings = {},
    selectedTemplateId = '',
    colorPaletteId = '',
    ...resumeData
  } = input || {};

  const clean = {};
  for (const [key, value] of Object.entries(resumeData)) {
    if (value === null || value === undefined) continue;

    // ===== PHOTO HARD-SKIP =====
    // A base64 photo is 100KB–2MB. Never store it in Firestore — it
    // would blow both our snapshot cap and the 1MB doc limit.
    if (key === 'photo' || key === 'photoRaw' || key === 'image' || key === 'profilePhoto') {
      continue;
    }

    if (typeof value === 'string') {
      const cap = FIELD_CAPS[key] || MAX_STRING_FIELD;
      clean[key] = asString(value, cap);
      continue;
    }
    if (typeof value === 'number' || typeof value === 'boolean') {
      clean[key] = value;
      continue;
    }
    // Nested objects/arrays from the client are ignored — snapshot stays flat.
  }

  const snapshot = {
    resumeData: clean,
    designSettings:
      designSettings && typeof designSettings === 'object' ? designSettings : {},
    selectedTemplateId: asString(selectedTemplateId, 64),
    colorPaletteId: asString(colorPaletteId, 64),
  };

  const size = JSON.stringify(snapshot).length;
  if (size > MAX_SNAPSHOT_BYTES) {
    throw new Error(
      `Resume data is too large to store for automatic PDF delivery (${size} bytes). Please shorten long text fields.`
    );
  }
  return snapshot;
}

// ============================================================
// 2. SERVER PDF TOKEN (HMAC, short-lived)
// ============================================================
function pdfSecret() {
  const secret =
    process.env.ENTITLEMENT_SECRET ||
    process.env.SERVER_PDF_SECRET ||
    '';
  if (!secret) throw new Error('ENTITLEMENT_SECRET is not configured.');
  return secret;
}

/**
 * Issues a token that lets the browser-side renderer fetch paid snapshot data
 * for the given paymentId without exposing the payment doc publicly.
 */
export function issueServerPdfToken(paymentId) {
  const payload = Buffer.from(
    JSON.stringify({
      paymentId,
      kind: 'pdf',
      exp: Date.now() + 30 * 60 * 1000, // 30 minutes
    })
  ).toString('base64url');

  const sig = crypto
    .createHmac('sha256', pdfSecret())
    .update(payload)
    .digest('base64url');

  return `${payload}.${sig}`;
}

/**
 * Verifies a token matches the given paymentId and hasn't expired.
 */
export function verifyServerPdfToken(token, paymentId) {
  if (!token || !paymentId) return false;

  const [payload, sig] = String(token).split('.');
  if (!payload || !sig) return false;

  const expected = crypto
    .createHmac('sha256', pdfSecret())
    .update(payload)
    .digest('base64url');

  if (expected.length !== sig.length) return false;
  if (!crypto.timingSafeEqual(Buffer.from(expected), Buffer.from(sig))) return false;

  try {
    const data = JSON.parse(Buffer.from(payload, 'base64url').toString('utf8'));
    return (
      data.paymentId === paymentId &&
      data.kind === 'pdf' &&
      Number(data.exp) > Date.now()
    );
  } catch {
    return false;
  }
}

// ============================================================
// 3. SNAPSHOT RETRIEVAL
// ============================================================
/**
 * Looks up the paid order by paymentId and returns the info needed to
 * render + email the PDF.
 *
 * @returns {Promise<null | {
 *   orderId: string, paymentId: string, templateId: string, templateName: string,
 *   amountPaise: number, currency: string,
 *   customerEmail: string, customerName: string,
 *   snapshot: object | null
 * }>}
 */
export async function getServerPdfSnapshot(paymentId) {
  if (!paymentId) return null;

  // Purchases doc uses paymentId as its ID (see api/server.js verifyPayment).
  const purchaseSnap = await db().collection('purchases').doc(paymentId).get();
  if (purchaseSnap.exists) {
    const data = purchaseSnap.data() || {};
    if (data.orderId) {
      const orderSnap = await db().collection('orders').doc(data.orderId).get();
      const order = orderSnap.exists ? orderSnap.data() || {} : {};
      return {
        orderId: data.orderId,
        paymentId,
        templateId: data.templateId || order.templateId || '',
        templateName: data.templateName || order.templateName || '',
        amountPaise: data.amountPaise || order.amountPaise || 0,
        currency: data.currency || order.currency || 'INR',
        customerEmail: data.customerEmail || order.customerEmail || '',
        customerName: data.customerName || order.customerName || '',
        snapshot: order.resumeSnapshot || null,
      };
    }
  }

  // Fallback: query orders by paymentId field.
  const snap = await db()
    .collection('orders')
    .where('paymentId', '==', paymentId)
    .limit(1)
    .get();

  if (snap.empty) return null;
  const doc = snap.docs[0];
  const data = doc.data() || {};

  return {
    orderId: data.orderId || doc.id,
    paymentId: data.paymentId || paymentId,
    templateId: data.templateId || '',
    templateName: data.templateName || '',
    amountPaise: data.amountPaise || 0,
    currency: data.currency || 'INR',
    customerEmail: data.customerEmail || '',
    customerName: data.customerName || '',
    snapshot: data.resumeSnapshot || null,
  };
}

// ============================================================
// 4. EMAIL DELIVERY IDEMPOTENCY
// ============================================================
function emailStateRef(paymentId) {
  return db().collection('emailDeliveries').doc(paymentId);
}

/**
 * Attempts to atomically claim the email-send slot for this payment.
 * Returns true if this caller is the one allowed to send; false if the
 * email was already sent or is currently being sent.
 *
 * Firestore's create() fails if the doc already exists — that's the
 * atomicity we need without a transaction.
 */
export async function claimEmailDelivery(paymentId) {
  if (!paymentId) return false;

  const ref = emailStateRef(paymentId);
  try {
    await ref.create({
      status: 'in_progress',
      startedAt: FieldValue.serverTimestamp(),
    });
    return true;
  } catch {
    return false;
  }
}

/**
 * Marks the email as delivered. Safe to call multiple times.
 */
export async function markEmailDelivered(paymentId, emailId = null) {
  if (!paymentId) return;
  await emailStateRef(paymentId).set(
    {
      status: 'delivered',
      emailId: emailId || null,
      deliveredAt: FieldValue.serverTimestamp(),
    },
    { merge: true }
  );
}

/**
 * Marks the email as failed with an optional error message.
 */
export async function markEmailDeliveryFailed(paymentId, error = null) {
  if (!paymentId) return;
  await emailStateRef(paymentId).set(
    {
      status: 'failed',
      error: error ? String(error).slice(0, 500) : null,
      failedAt: FieldValue.serverTimestamp(),
    },
    { merge: true }
  );
}
